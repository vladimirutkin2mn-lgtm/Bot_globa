"""Versioned Tarot domain data for deterministic Rider–Waite–Smith readings.

The legacy Major-Arcana-only catalog remains available for already versioned behavior.
New readings use the 78-card RWS-derived catalog. Meanings are concise Russian
paraphrases of the Waite/Smith tradition rather than quotations from source material.
"""

from dataclasses import dataclass
from enum import StrEnum


class TarotArcana(StrEnum):
    MAJOR = "major"
    MINOR = "minor"


class TarotSuit(StrEnum):
    WANDS = "wands"
    CUPS = "cups"
    SWORDS = "swords"
    PENTACLES = "pentacles"


@dataclass(frozen=True, slots=True)
class TarotCard:
    code: str
    name_ru: str
    arcana: TarotArcana
    suit: TarotSuit | None
    rank: str | None
    upright_theme: str
    reversed_theme: str
    symbolic_focus: str

    def __post_init__(self) -> None:
        if not self.code or not self.name_ru.strip():
            raise ValueError("tarot card requires code and display name")
        if self.arcana is TarotArcana.MAJOR and (self.suit is not None or self.rank is not None):
            raise ValueError("major arcana cannot have a suit or rank")
        if self.arcana is TarotArcana.MINOR and (self.suit is None or self.rank is None):
            raise ValueError("minor arcana requires suit and rank")
        if not self.upright_theme.strip() or not self.reversed_theme.strip():
            raise ValueError("tarot card requires upright and reversed meanings")
        if not self.symbolic_focus.strip():
            raise ValueError("tarot card requires symbolic focus")


@dataclass(frozen=True, slots=True)
class TarotSpread:
    code: str
    positions: tuple[str, ...]
    allow_reversed: bool = True

    def __post_init__(self) -> None:
        if not self.code or not self.positions:
            raise ValueError("tarot spread requires code and positions")
        if len(self.positions) != len(set(self.positions)):
            raise ValueError("tarot spread positions must be unique")


@dataclass(frozen=True, slots=True)
class TarotCatalog:
    version: str
    cards: tuple[TarotCard, ...]

    def __post_init__(self) -> None:
        codes = [card.code for card in self.cards]
        if not self.version:
            raise ValueError("tarot catalog version is required")
        if not cards_are_unique(codes):
            raise ValueError("tarot card codes must be unique")


def cards_are_unique(codes: list[str]) -> bool:
    return len(codes) == len(set(codes))


def _major(
    code: str,
    name_ru: str,
    upright_theme: str,
    reversed_theme: str,
    symbolic_focus: str,
) -> TarotCard:
    return TarotCard(
        code=code,
        name_ru=name_ru,
        arcana=TarotArcana.MAJOR,
        suit=None,
        rank=None,
        upright_theme=upright_theme,
        reversed_theme=reversed_theme,
        symbolic_focus=symbolic_focus,
    )


def _minor(
    suit: TarotSuit,
    rank: str,
    name_ru: str,
    upright_theme: str,
    reversed_theme: str,
    symbolic_focus: str,
) -> TarotCard:
    return TarotCard(
        code=f"{suit.value}_{rank}",
        name_ru=name_ru,
        arcana=TarotArcana.MINOR,
        suit=suit,
        rank=rank,
        upright_theme=upright_theme,
        reversed_theme=reversed_theme,
        symbolic_focus=symbolic_focus,
    )


